import { createReadStream } from 'node:fs';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';

/** Where image bytes live. Local disk today; an S3-compatible driver can replace it later. */
export interface StorageDriver {
  put(key: string, data: Buffer): Promise<void>;
  read(key: string): Promise<Buffer>;
  stream(key: string): Readable;
  exists(key: string): Promise<boolean>;
  remove(key: string): Promise<void>;
}

export const STORAGE = Symbol('STORAGE');

export const storageKeys = {
  original: (imageId: string, extension: string) => `originals/${imageId}.${extension}`,
  reveal: (imageId: string) => `reveal/${imageId}.webp`,
  crop: (zoomPointId: string, level: number, sizePx: number) =>
    `crops/${zoomPointId}/${level}-${sizePx}.webp`,
};

export class LocalStorage implements StorageDriver {
  private readonly root: string;

  constructor(rootDir: string) {
    this.root = resolve(rootDir);
  }

  /** Keys are generated by the server, but a key must never be able to leave the root. */
  private path(key: string): string {
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new Error(`Storage key escapes the root: ${key}`);
    return full;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, data);
  }

  read(key: string): Promise<Buffer> {
    return readFile(this.path(key));
  }

  stream(key: string): Readable {
    return createReadStream(this.path(key));
  }

  async exists(key: string): Promise<boolean> {
    return stat(this.path(key)).then(
      (s) => s.isFile(),
      () => false,
    );
  }

  async remove(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }
}
